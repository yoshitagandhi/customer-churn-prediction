"""Model performance page.

Displays evaluation artifacts generated by Milestone 7 (and the
optimized threshold from Milestone 9) — never recomputes any metric.
"""

import pandas as pd
import streamlit as st

from app.components.charts import render_saved_figure
from app.components.tables import render_model_comparison_table
from configs.config import settings
from configs.logging_config import get_logger
from configs.paths import FIGURES_DIR

logger = get_logger(__name__)


def render_model_performance() -> None:
    """Render the model performance dashboard from existing evaluation artifacts."""
    st.header("Model Performance")
    st.write("Evaluation results computed during model training and evaluation (Milestones 6–7).")

    if settings.model_ranking_path.exists():
        st.subheader("Model Comparison")
        render_model_comparison_table(pd.read_csv(settings.model_ranking_path))
    else:
        st.info("Model ranking not found yet. Run the evaluation pipeline first.")

    st.subheader("ROC and Precision-Recall Curves")
    curve_col1, curve_col2 = st.columns(2)
    with curve_col1:
        render_saved_figure("roc_curve.png", caption="ROC Curve")
    with curve_col2:
        render_saved_figure("precision_recall_curve.png", caption="Precision-Recall Curve")

    st.subheader("Calibration and Learning Curve")
    diag_col1, diag_col2 = st.columns(2)
    with diag_col1:
        render_saved_figure("calibration_curve.png", caption="Calibration Curve")
    with diag_col2:
        render_saved_figure("learning_curve.png", caption="Learning Curve")

    st.subheader("Confusion Matrices")
    if FIGURES_DIR.exists():
        for figure_path in sorted(FIGURES_DIR.glob("confusion_matrix_*.png")):
            render_saved_figure(figure_path.name)

    if settings.threshold_config_path.exists():
        st.divider()
        st.subheader("Optimized Decision Threshold")
        render_saved_figure(
            "optimal_threshold_confusion_matrix.png",
            caption="Confusion Matrix at Optimal Threshold",
        )
