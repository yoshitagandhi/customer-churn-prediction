"""Reusable plotting primitives.

This module provides small, composable plotting functions used by
:mod:`src.visualization.distributions` and
:mod:`src.visualization.business_charts`. Keeping them here avoids
duplicating figure styling, saving, and layout logic across the
codebase.

Every function saves its figure as a PNG under
``configs.paths.FIGURES_DIR`` (or a caller-supplied directory) and
returns the path it was saved to.
"""

import matplotlib

matplotlib.use("Agg")  # Non-interactive backend; this project only saves PNGs.

from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns

from configs.logging_config import get_logger
from configs.paths import FIGURES_DIR

logger = get_logger(__name__)

_FIGURE_SIZE = (8, 5)
_DPI = 150
_PALETTE = "viridis"


def configure_plot_style() -> None:
    """Apply consistent styling across all figures generated by this project."""
    sns.set_theme(style="whitegrid", palette=_PALETTE)
    plt.rcParams["figure.figsize"] = _FIGURE_SIZE
    plt.rcParams["figure.dpi"] = _DPI
    plt.rcParams["axes.titlesize"] = 13
    plt.rcParams["axes.titleweight"] = "bold"
    plt.rcParams["axes.labelsize"] = 11


def save_figure(figure: plt.Figure, filename: str, output_dir: Path = FIGURES_DIR) -> Path:
    """Save a Matplotlib figure to disk and close it to free memory.

    Args:
        figure: The figure to save.
        filename: Output filename, e.g. "target_distribution.png".
        output_dir: Directory to save into. Defaults to
            ``configs.paths.FIGURES_DIR``.

    Returns:
        The path the figure was saved to.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / filename
    figure.tight_layout()
    figure.savefig(output_path, dpi=_DPI, bbox_inches="tight")
    plt.close(figure)
    logger.debug("Saved figure: %s", output_path)
    return output_path


def plot_histogram(
    series: pd.Series,
    title: str,
    filename: str,
    *,
    bins: int = 30,
    kde: bool = True,
    output_dir: Path = FIGURES_DIR,
) -> Path:
    """Plot a histogram (optionally with a KDE overlay) for a numeric series.

    Args:
        series: Numeric data to plot.
        title: Figure title.
        filename: Output filename.
        bins: Number of histogram bins.
        kde: Whether to overlay a kernel density estimate.
        output_dir: Directory to save into.

    Returns:
        The path the figure was saved to.
    """
    figure, axis = plt.subplots()
    sns.histplot(series.dropna(), bins=bins, kde=kde, ax=axis, color=sns.color_palette(_PALETTE)[0])
    axis.set_title(title)
    axis.set_xlabel(series.name)
    axis.set_ylabel("Count")
    return save_figure(figure, filename, output_dir)


def plot_boxplot(
    dataframe: pd.DataFrame,
    numeric_column: str,
    title: str,
    filename: str,
    *,
    by: str | None = None,
    output_dir: Path = FIGURES_DIR,
) -> Path:
    """Plot a boxplot for a numeric column, optionally grouped by another column.

    Args:
        dataframe: Source data.
        numeric_column: Numeric column to plot.
        title: Figure title.
        filename: Output filename.
        by: Optional categorical column to group boxes by (e.g., the
            target column).
        output_dir: Directory to save into.

    Returns:
        The path the figure was saved to.
    """
    figure, axis = plt.subplots()
    if by is not None:
        sns.boxplot(data=dataframe, x=by, y=numeric_column, ax=axis, hue=by, legend=False)
    else:
        sns.boxplot(data=dataframe, y=numeric_column, ax=axis)
    axis.set_title(title)
    return save_figure(figure, filename, output_dir)


def plot_violin(
    dataframe: pd.DataFrame,
    numeric_column: str,
    category_column: str,
    title: str,
    filename: str,
    output_dir: Path = FIGURES_DIR,
) -> Path:
    """Plot a violin plot of a numeric column split by a categorical column.

    Args:
        dataframe: Source data.
        numeric_column: Numeric column to plot.
        category_column: Categorical column to split by.
        title: Figure title.
        filename: Output filename.
        output_dir: Directory to save into.

    Returns:
        The path the figure was saved to.
    """
    figure, axis = plt.subplots()
    sns.violinplot(
        data=dataframe,
        x=category_column,
        y=numeric_column,
        ax=axis,
        hue=category_column,
        legend=False,
    )
    axis.set_title(title)
    return save_figure(figure, filename, output_dir)


def _annotate_bars_with_percentage(axis: plt.Axes, total: int) -> None:
    """Annotate each bar in a bar/count plot with its count and percentage.

    Args:
        axis: The Matplotlib axis containing the bars.
        total: The total number of observations, used to compute
            each bar's percentage share.
    """
    for patch in axis.patches:
        height = patch.get_height()
        if height <= 0:
            continue
        percentage = height / total * 100
        axis.annotate(
            f"{int(height)} ({percentage:.1f}%)",
            xy=(patch.get_x() + patch.get_width() / 2, height),
            xytext=(0, 4),
            textcoords="offset points",
            ha="center",
            fontsize=8,
        )


def plot_countplot(
    dataframe: pd.DataFrame,
    category_column: str,
    title: str,
    filename: str,
    *,
    hue: str | None = None,
    output_dir: Path = FIGURES_DIR,
) -> Path:
    """Plot a count plot for a categorical column, annotated with percentages.

    Args:
        dataframe: Source data.
        category_column: Categorical column to count.
        title: Figure title.
        filename: Output filename.
        hue: Optional column to split bars by (e.g., the target column).
            When set, percentage annotations are omitted since bars no
            longer sum to the dataset total.
        output_dir: Directory to save into.

    Returns:
        The path the figure was saved to.
    """
    figure, axis = plt.subplots()
    order = dataframe[category_column].value_counts().index
    sns.countplot(data=dataframe, x=category_column, hue=hue, order=order, ax=axis)
    if hue is None:
        _annotate_bars_with_percentage(axis, total=len(dataframe))
    axis.set_title(title)
    axis.tick_params(axis="x", rotation=30)
    return save_figure(figure, filename, output_dir)


def plot_correlation_heatmap(
    correlation_matrix: pd.DataFrame,
    title: str = "Correlation Heatmap",
    filename: str = "correlation_heatmap.png",
    output_dir: Path = FIGURES_DIR,
) -> Path:
    """Plot a heatmap of a correlation matrix.

    Args:
        correlation_matrix: Square correlation matrix to visualize.
        title: Figure title.
        filename: Output filename.
        output_dir: Directory to save into.

    Returns:
        The path the figure was saved to.
    """
    figure, axis = plt.subplots(figsize=(6, 5))
    sns.heatmap(correlation_matrix, annot=True, fmt=".2f", cmap="coolwarm", center=0, ax=axis)
    axis.set_title(title)
    return save_figure(figure, filename, output_dir)


def plot_bar_from_series(
    series: pd.Series,
    title: str,
    filename: str,
    *,
    xlabel: str = "",
    ylabel: str = "",
    value_suffix: str = "",
    output_dir: Path = FIGURES_DIR,
) -> Path:
    """Plot a bar chart from a pre-computed Series, annotated with values.

    Useful for charts derived from aggregated statistics (e.g., churn
    rate per category) rather than raw row-level data.

    Args:
        series: Index becomes the x-axis categories; values become
            bar heights.
        title: Figure title.
        filename: Output filename.
        xlabel: X-axis label.
        ylabel: Y-axis label.
        value_suffix: Text appended to each bar's value annotation
            (e.g., "%").
        output_dir: Directory to save into.

    Returns:
        The path the figure was saved to.
    """
    figure, axis = plt.subplots()
    bars = axis.bar(
        series.index.astype(str), series.values, color=sns.color_palette(_PALETTE, len(series))
    )
    for bar, value in zip(bars, series.values, strict=True):
        axis.annotate(
            f"{value:.1f}{value_suffix}",
            xy=(bar.get_x() + bar.get_width() / 2, bar.get_height()),
            xytext=(0, 4),
            textcoords="offset points",
            ha="center",
            fontsize=9,
        )
    axis.set_title(title)
    axis.set_xlabel(xlabel)
    axis.set_ylabel(ylabel)
    axis.tick_params(axis="x", rotation=30)
    return save_figure(figure, filename, output_dir)


def plot_target_distribution(
    dataframe: pd.DataFrame,
    target_column: str,
    title: str = "Target Distribution",
    filename: str = "target_distribution.png",
    output_dir: Path = FIGURES_DIR,
) -> Path:
    """Plot the target class distribution with count and percentage labels.

    This is a thin, semantically-named wrapper around
    :func:`plot_countplot` to keep the target-distribution chart
    consistent with every other count-based chart in this project.

    Args:
        dataframe: Source data.
        target_column: Name of the target column.
        title: Figure title.
        filename: Output filename.
        output_dir: Directory to save into.

    Returns:
        The path the figure was saved to.
    """
    return plot_countplot(dataframe, target_column, title, filename, output_dir=output_dir)
