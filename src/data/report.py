"""Data quality report generation.

This module converts the outputs of the dataset validator and profiler
into machine-readable and human-readable reports. The reports summarize
dataset characteristics, validation findings, and recommended actions.
The module never modifies the dataset itself.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from configs.config import settings
from configs.logging_config import get_logger
from src.data.validator import ValidationResult

logger = get_logger(__name__)

_JSON_REPORT_FILENAME = "data_quality_report.json"
_MARKDOWN_REPORT_FILENAME = "data_quality_summary.md"
_REPORT_VERSION = 1
_JSON_INDENT = 2
_ENCODING = "utf-8"

def generate_quality_report(
    validation_result: ValidationResult,
    profile: dict[str, Any],
    output_dir: Path = settings.report_dir,
) -> dict[str, Path]:
    """Generate JSON and Markdown data quality reports.

    Two report files are produced:

    * ``data_quality_report.json`` – structured machine-readable report.
    * ``data_quality_summary.md`` – human-readable Markdown report.

    Args:
        validation_result:
            Validation output produced by
            :func:`src.data.validator.validate_dataset`.

        profile:
            Dataset metadata generated by
            :func:`src.data.profiler.profile_dataset`.

        output_dir:
            Directory where reports will be written.

    Returns:
        Dictionary containing the generated report paths.
    """
    logger.info("Generating data quality reports.")

    report_data = _build_report_data(
        validation_result=validation_result,
        profile=profile,
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    json_path = output_dir / _JSON_REPORT_FILENAME
    markdown_path = output_dir / _MARKDOWN_REPORT_FILENAME

    _write_json_report(
        json_path,
        report_data,
    )

    _write_markdown_report(
        markdown_path,
        report_data,
    )

    logger.info(
        "Generated data quality reports successfully."
    )

    logger.debug(
        "JSON report: %s | Markdown report: %s",
        json_path,
        markdown_path,
    )

    return {
        "json": json_path,
        "markdown": markdown_path,
    }


def _write_json_report(
    output_path: Path,
    report: dict[str, Any],
) -> None:
    """Write the JSON report to disk."""

    output_path.write_text(
        json.dumps(
            report,
            indent=_JSON_INDENT,
            default=str,
        ),
        encoding=_ENCODING,
    )

def _render_markdown(
    report: dict[str, Any],
) -> str:
    """Render the data quality report as Markdown."""

    overview = report["dataset_overview"]
    validation = report["validation_summary"]
    duplicate = report["duplicate_summary"]

    lines: list[str] = [
        "# Data Quality Summary",
        "",
        f"Generated at: {report['generated_at']}",
        "",
        "## Dataset overview",
        f"- Rows: {overview['rows']}",
        f"- Columns: {overview['columns']}",
        f"- Memory usage (MB): {overview['memory_usage_mb']}",
        f"- Target column: {overview['target_column']}",
        "",
        "### Target distribution",
    ]

    for label, count in overview["target_distribution"].items():
        lines.append(f"- {label}: {count}")

    lines.extend([
        "",
        "## Validation summary",
    ])

    if validation["passed_checks"]:
        lines.append("### Passed checks")
        for check in validation["passed_checks"]:
            lines.append(f"- {check}")
        lines.append("")

    if validation["warnings"]:
        lines.append("### Warnings")
        for warning in validation["warnings"]:
            lines.append(f"- {warning['check']}: {warning['message']}")
        lines.append("")

    if validation["failed_checks"]:
        lines.append("### Failed checks")
        for error in validation["failed_checks"]:
            lines.append(f"- {error['check']}: {error['message']}")
        lines.append("")

    lines.extend([
        "## Missing values",
    ])

    if report["missing_values"]:
        for column, stats in report["missing_values"].items():
            lines.append(f"- {column}: {stats}")
    else:
        lines.append("- No missing values detected.")

    lines.extend([
        "",
        "## Duplicate summary",
        f"- Duplicate rows: {duplicate['duplicate_row_count']}",
        f"- Duplicate customer IDs: {duplicate['duplicate_customer_id_count']}",
        "",
        "## Recommendations",
    ])

    for recommendation in report["recommendations"]:
        lines.append(f"- {recommendation}")

    return "\n".join(lines)

def _write_markdown_report(
    output_path: Path,
    report: dict[str, Any],
) -> None:
    """Write the Markdown report to disk."""

    output_path.write_text(
        _render_markdown(report),
        encoding=_ENCODING,
    )

def _build_report_data(
    validation_result: ValidationResult,
    profile: dict[str, Any],
) -> dict[str, Any]:
    """Assemble the structured report shared by all output formats.

    Args:
        validation_result:
            Output produced by the dataset validator.

        profile:
            Dataset metadata generated by the profiler.

    Returns:
        Dictionary containing all information required to generate
        JSON and Markdown reports.
    """
    missing_values_issue = validation_result.get_issue(
        "missing_values"
    )

    duplicate_rows_issue = validation_result.get_issue(
        "duplicate_rows"
    )

    duplicate_identifiers_issue = validation_result.get_issue(
        "duplicate_identifiers"
    )

    report = {
        "report_version": _REPORT_VERSION,
        "generated_at": datetime.now(
            UTC
        ).isoformat(),
        "dataset_overview": {
            "rows": profile["total_rows"],
            "columns": profile["total_columns"],
            "memory_usage_mb": profile["memory_usage_mb"],
            "target_column": profile["target_column"],
            "target_distribution": profile[
                "target_distribution"
            ],
        },
        "validation_summary": {
            "passed_checks": [
                issue.check_name
                for issue in validation_result.passed
            ],
            "warnings": [
                {
                    "check": issue.check_name,
                    "message": issue.message,
                }
                for issue in validation_result.warnings
            ],
            "failed_checks": [
                {
                    "check": issue.check_name,
                    "message": issue.message,
                }
                for issue in validation_result.errors
            ],
        },
        "missing_values": (
            missing_values_issue.details
            if missing_values_issue is not None
            else {}
        ),
        "duplicate_summary": {
            "total_rows": profile["total_rows"],
            "duplicate_row_count": _get_detail(
                duplicate_rows_issue,
                "duplicate_row_count",
            ),
            "duplicate_customer_id_count": _get_detail(
                duplicate_identifiers_issue,
                "duplicate_id_count",
            ),
        },
        "datatype_summary": {
            "numeric": profile["numeric_features"],
            "categorical": profile[
                "categorical_features"
            ],
            "binary": profile["binary_features"],
        },
        "recommendations": _generate_recommendations(
            validation_result
        ),
    }

    return report

def _get_detail(
    issue: Any,
    key: str,
    default: int = 0,
) -> int:
    """Safely retrieve a value from a validation issue."""

    if issue is None:
        return default

    details = issue.details or {}

    return details.get(
        key,
        default,
    )
    
def _generate_recommendations(
    validation_result: ValidationResult,
) -> list[str]:
    """Generate recommendations from validation findings."""

    recommendations: list[str] = []

    datatype_issue = validation_result.get_issue(
        "datatype_consistency"
    )

    if (
        datatype_issue is not None
        and datatype_issue.severity == "WARNING"
    ):
        for (
            column,
            dtype,
        ) in datatype_issue.details.get(
            "mismatched_columns",
            {},
        ).items():
            recommendations.append(
                f"Convert '{column}' to a numeric data type "
                f"(currently '{dtype}')."
            )

    missing_values_issue = validation_result.get_issue(
        "missing_values"
    )

    if (
        missing_values_issue is not None
        and missing_values_issue.severity == "WARNING"
    ):
        for (
            column,
            statistics,
        ) in missing_values_issue.details.items():
            recommendations.append(
                f"Handle missing values in '{column}' "
                f"({statistics['missing_percentage']}% missing)."
            )

    duplicate_rows = _get_detail(
        validation_result.get_issue(
            "duplicate_rows"
        ),
        "duplicate_row_count",
    )

    if duplicate_rows > 0:
        recommendations.append(
            "Remove duplicate rows before model training."
        )

    duplicate_ids = _get_detail(
        validation_result.get_issue(
            "duplicate_identifiers"
        ),
        "duplicate_id_count",
    )

    if duplicate_ids > 0:
        recommendations.append(
            "Investigate duplicate customer identifiers."
        )

    if not recommendations:
        recommendations.append(
            "No significant data quality issues detected. "
            "Dataset is ready for exploratory analysis."
        )

    return recommendations

