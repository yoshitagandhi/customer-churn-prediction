def _render_overview_section(
    overview: dict[str, Any],
) -> str:
    """Render the dataset overview section."""

    lines = [
        "## Dataset Overview",
        "",
        f"- Rows: {overview['rows']}",
        f"- Columns: {overview['columns']}",
        f"- Target column: `{overview['target_column']}`",
        f"- Memory usage: {overview['memory_usage_mb']} MB",
    ]

    target_distribution = overview.get(
        "target_distribution"
    )

    if target_distribution:
        lines.append("")
        lines.append("### Target Distribution")
        lines.append("")

        for label, statistics in target_distribution.items():
            lines.append(
                f"- **{label}**: "
                f"{statistics['count']} "
                f"({statistics['percentage']}%)"
            )

    return "\n".join(lines)

def _render_missing_values_section(
    missing_values: dict[str, Any],
) -> str:
    """Render the missing values section."""

    if not missing_values:
        return (
            "## Missing Values\n\n"
            "No missing values detected."
        )

    lines = [
        "## Missing Values",
        "",
        "| Column | Missing Count | Missing % |",
        "| --- | ---: | ---: |",
    ]

    for column, statistics in missing_values.items():
        safe_column = column.replace("|", r"\|")

        lines.append(
            f"| {safe_column} | "
            f"{statistics['missing_count']} | "
            f"{statistics['missing_percentage']}% |"
        )

    return "\n".join(lines)

def _render_datatype_section(
    datatype_summary: dict[str, Any],
) -> str:
    """Render datatype information."""

    numeric = (
        ", ".join(datatype_summary["numeric"])
        or "None"
    )

    categorical = (
        ", ".join(
            datatype_summary["categorical"]
        )
        or "None"
    )

    binary = (
        ", ".join(datatype_summary["binary"])
        or "None"
    )

    lines = [
        "## Datatype Summary",
        "",
        f"- Numeric columns: {numeric}",
        f"- Categorical columns: {categorical}",
        f"- Binary columns: {binary}",
    ]

    return "\n".join(lines)

def _render_recommendations_section(
    recommendations: list[str],
) -> str:
    """Render recommendations."""

    lines = [
        "## Recommendations",
        "",
    ]

    lines.extend(
        f"- {recommendation}"
        for recommendation in recommendations
    )

    return "\n".join(lines)